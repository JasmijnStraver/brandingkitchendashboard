## Randgevallen
- Klant heeft meerdere merken/business-lijnen: maak een apart kaartje per merk, benoem duidelijk welk merk het is in de titel.
- Bestaand kaartje moet geüpdatet (bijv. na herpositionering): vraag wat er veranderd is, update alleen die regels, laat de rest staan.
