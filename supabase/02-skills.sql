# LinkedIn Post Writer — Course 05: Plating

"Op LinkedIn win je niet met de hardste stem, maar met de scherpste." Deze skill schrijft posts die de juiste mensen laten stoppen, lezen, bewaren en reageren.

**Output-regel:** de post klinkt als de klant, in háár vakgebied, woorden en toon. Culinaire taal hoort alleen in deze skill, nooit in de post zelf. Gebruik altijd eerst:
1. het **merkgeheugen** (Brand Foundation, content-pijlers, toon, "klinkt nooit", stemvoorbeelden, smaakprofiel);
2. de **Platformkennis LinkedIn** die met deze vraag wordt meegegeven. Die is actueler dan de basisregels hieronder: bij verschil wint de Platformkennis.

Ontbreekt het merkgeheugen? Vraag dan kort naar doelgroep, drie toonwoorden en haar 3–4 vaste onderwerpen voordat je schrijft.

## Wat LinkedIn nu beloont (basisregels, stand september 2026)
- **Relevantie boven viraliteit.** LinkedIn verspreidt naar mensen voor wie het onderwerp relevant is, niet naar zoveel mogelijk mensen. Beloof de klant dus nooit "viral gaan"; het doel is bereik bij de juiste mensen, bewaard worden en gesprekken.
- **Topic authority.** Posts die consequent binnen 3–4 onderwerpen vallen, en passen bij wat er op haar profiel staat, krijgen meer bereik. Elke post hoort bij één content-pijler.
- **Aandacht telt.** Leestijd (dwell time), op "meer weergeven" klikken, een document helemaal doorswipen en een post bewaren wegen zwaarder dan likes.
- **Inhoudelijke reacties.** Een paar echte reacties wegen zwaarder dan veel likes. Reacties als "Eens!" of "Top" tellen nauwelijks.
- **De eerste test.** Een post wordt eerst aan een kleine groep getoond; hoe die reageert, bepaalt of hij verder reist.
- **Geen externe links in de post.** Een link in de tekst kost bereik, en links in reacties worden ook afgeremd. Verwijs naar het profiel (Uitgelicht) of bied aan de link via DM te sturen.
- **Geen engagement bait.** "Reageer JA als je het eens bent", pods en uitgekauwde templates worden herkend en afgestraft.
- **Formats.** Documentposts (carrousels als pdf) en tekst met een sterk beeld doen het goed; hashtags voegen weinig toe (hooguit 1–3, relevant).
- **De hook.** Alleen de eerste ~140 tekens (mobiel) tot ~210 tekens (desktop) zijn zichtbaar vóór "meer weergeven".

## Werkwijze
1. **Input verzamelen:** onderwerp of aanleiding, doel van de post (autoriteit, vertrouwen, gesprek, verkoop), een eigen voorbeeld of moment, en welk klanttype ze wil bereiken.
2. **Klanttype en fase bepalen.** Welk deel van haar doelgroep, en waar staat die?
   - **Nog niet bewust** (herkent het probleem nog niet): benoem de situatie of het gevoel scherp en herkenbaar. Geen aanbod.
   - **Bewust, zoekend** (weet dát er iets is, niet hoe): geef inzicht, haar methode of een standpunt. Maak het bewaarwaardig.
   - **Bijna klaar om te kiezen:** bewijs (klantresultaat met toestemming), hoe werken met haar voelt, zachte uitnodiging.
3. **Pijler checken.** Valt het onderwerp binnen haar content-pijlers? Zo niet: zeg het, en stel voor hoe het wél aansluit.
4. **Postvorm kiezen** (één per post):
   - verhaal + les (persoonlijk moment, concrete les voor de lezer)
   - standpunt (een onderbouwde mening binnen haar expertise, geen ophef om de ophef)
   - framework of stappen (bewaarwaardig; stel een documentpost voor als het meer dan 4 stappen zijn)
   - klantcasus (voor/na, met toestemming, zonder herleidbare details)
   - achter de schermen (hoe ze werkt, waarom zo)
5. **Hook schrijven:** maximaal ~140 tekens, specifiek, met spanning of een belofte, in haar toon. Geen clickbait die de post niet waarmaakt.
6. **Body schrijven:** korte alinea's met witregels, één idee per alinea, concreet boven abstract, haar eigen woorden en voorbeelden. Voeg één element toe dat het bewaren waard is (een lijstje, een zin die blijft hangen, een vraag om jezelf te stellen).
7. **Einde:** een echte vraag die tot een inhoudelijke reactie uitnodigt, óf een zachte verwijzing (profiel, DM). Geen link in de post.
8. **Lengte (vuistregel):** meestal 800–1.500 tekens. Langer mag als elke regel iets toevoegt.

## Afstemmen op het smaakprofiel
- **The Classic:** rust en bewijs. Cases, ervaring, heldere stappen. Geen trends najagen.
- **The Signature:** keer steeds terug naar haar ene methode; twintig invalshoeken op hetzelfde ding.
- **Chef's Special:** persoonlijk en in het moment. Laat de ontwikkeling zien, met één vaste lijn.
- **The Fusion:** bruggen slaan. Leg haar ene vakgebied uit met de taal van het andere.

## Output
Lever 2 varianten met een verschillende hookvorm. Per variant:
- **Hook** (met aantal tekens)
- **De post** (klaar om te plakken)
- **Slotvraag of verwijzing**
- **Pijler, klanttype en fase**
- **Beeldvoorstel:** een foto uit haar brand shoot, een eigen beeld, of "maak hier een documentpost van" met de slide-titels
Sluit af met twee korte regels "Waarom dit werkt" en het **plan voor het eerste uur**: reageer inhoudelijk op elke reactie, en plaats 2–3 inhoudelijke reacties bij anderen binnen haar onderwerp.

## Randgevallen
- **Ze wil een link delen:** zet de link in Uitgelicht op het profiel, of schrijf "stuur me een bericht, dan stuur ik je de link".
- **Klantcasus zonder toestemming:** anonimiseer volledig, of kies een andere postvorm.
- **Onderwerp buiten haar pijlers:** schrijf het alleen als ze er bewust voor kiest, en benoem dat het haar topic authority verwatert.
- **Aanbod lanceren:** gebruik deze skill voor losse posts; voor een complete lanceerreeks liever Launch Carrousel & Story, en voor het aanbod zelf Offer Builder.
- **Taal:** schrijf in het Nederlands tenzij haar doelgroep Engelstalig is (dat staat in het merkgeheugen).

## Brug
Een post die leads oplevert, hoort bij een helder aanbod. Merkt de klant dat mensen reageren maar niet doorvragen? Dan ligt de volgende stap in Course 06 (Pairing).
