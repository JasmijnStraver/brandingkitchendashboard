1. Voor wie is dit (specifieke doelgroep, geen "iedereen die...")
2. Wat is het resultaat/de transformatie die ze leveren
3. Wat maakt hun aanpak anders dan de standaard in hún markt/vakgebied — dit is de kern van de Positioning Cut
4. Wat ergert hen aan hoe anderen in hún vakgebied het aanpakken (dit voedt de anti-positionering)
5. **Raw Ingredients-check**: is dit echt van hén — hun eigen verhaal, expertise, rafelrandjes — of leunen ze op een aanpak/frame die ze ergens hebben opgepikt en niet echt hun eigen "smaak" is?
6. Gewenste toon (**Flavor Profile**): confronterend, warm, luxueus, speels, zakelijk — laat ze kiezen of geef 2-3 opties passend bij hún vakgebied (niet TBK's eigen toon opdringen)

