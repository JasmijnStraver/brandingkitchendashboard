### Stap 2 — Bouw de vier onderdelen (in de taal van de klant, niet in TBK-jargon)

**Kernbelofte** — één zin. Het resultaat + voor wie + zonder de standaard-aanpak. Geen "ik help [doelgroep] met [vaag ding]". Test: zou een concurrent deze zin ook kunnen claimen? Zo ja, te generiek — scherper.

**Content-pijlers** — 3-4 terugkerende thema's die alle content voeden. Elke pijler krijgt:
- Naam (kort, memorabel)
- Waar het over gaat (1-2 zinnen)
- Wat voor content-type erbij past (bijv. carrousel, story, hook)

**Anti-positionering** — wat dit merk NIET is, expliciet tegenover de markt-norm. Dit is vaak het scherpste onderdeel: benoem 2-3 concrete dingen die de "standaard" aanpak wél doet en dit merk bewust niet. Confronterend, niet aanvallend.

**Toon-van-stem regels** — 4-6 concrete regels (geen abstracte bijvoeglijke naamwoorden). Elke regel heeft een "wel" en een "nooit". Voorbeeld-formaat:
- Wel: korte, ritmische zinnen. Nooit: opsommingen van vage voordelen.
- Wel: concrete beelden. Nooit: containerbegrippen als "impact maken" of "je beste zelf".

