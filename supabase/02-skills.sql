# Brand Foundation

Een kort, herbruikbaar referentiekaartje per klant/business — de destillatie van Course 04 (Positioning Cut), met een tikkeltje Course 01 (Raw Ingredients) en Course 02 (Flavor Profile). Doel: andere skills (Caption Writer, Hook Generator, Carrousel-skills, etc.) kunnen dit aan het begin van een sessie meekrijgen en meteen door naar het eigenlijke werk, zonder opnieuw "voor wie is dit" en "wat is je toon" te vragen.

## Wanneer gebruiken
- Direct na afronding van een Messaging Plan (Course 04) — condenseer het resultaat tot dit kaartje
- Los, wanneer iemand vraagt om hun merkbasis vast te leggen of samen te vatten
- Als een andere content-skill start voor een klant zonder dat er al een Brand Foundation is: bouw 'm dan eerst (kort, niet de volledige Messaging Plan-intake) voordat je verder gaat met de eigenlijke taak

## Werkwijze

### Als er al een Messaging Plan-output in het gesprek/de documenten staat
Condenseer die naar het kaartje-formaat hieronder — geen nieuwe vragen nodig, alleen samenvatten en verdichten.

### Als er nog niets bestaat
Stel alleen de vier essentiële vragen (niet de volledige Messaging Plan-intake):
1. Voor wie is dit, en wat is het resultaat dat ze leveren?
2. Wat maakt de aanpak anders dan de standaard in hún vakgebied?
3. Gewenste toon (2-4 kernwoorden, geen alinea)
4. Iets dat ze NOOIT willen klinken (voedt de "nooit"-regel)

Houd dit kort — dit is geen volwaardige Messaging Plan-sessie, alleen de minimale basis om andere skills te voeden. Verwijs naar de Messaging Plan-skill als iemand een uitgebreidere, scherpere versie wil.

## Output-formaat
Lever een compact kaartje, geen lang document — dit moet in één oogopslag te scannen zijn en makkelijk te plakken aan het begin van een andere skill-sessie:

```
BRAND FOUNDATION — [merknaam/klant]
Doelgroep: [één zin]
Kernbelofte: [één zin]
Positionering (wat dit NIET is): [1-2 punten]
Toon: [3-5 kernwoorden] — nooit: [1-2 dingen]
Content-pijlers: [alleen namen, geen uitleg — max 4]
```

Geen culinaire kopjes in de output zelf (zelfde regel als bij Messaging Plan) — wel mag je er in de intro bij zetten dat dit de destillatie is van Course 04 (met 01/02).

## Hergebruik door andere skills
