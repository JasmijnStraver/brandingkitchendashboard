**Belangrijk — voor wie is de output:** de vragen en het proces volgen de 7-Course logica, maar het geleverde document is voor de eindklant (de coach/consultant/freelancer zelf) en moet klinken als hún merk — niet als TBK's eigen fine-dining-merktaal. Gebruik dus GEEN culinaire labels in de output-secties (geen "Signature Sauce", geen "Raw Ingredients" als kopje) — de klant kan een voedingscoach, interieurontwerper of jurist zijn, en het document moet in hún wereld passen. De culinaire framing hoort alleen bij de intro (welke gang dit is) en de afsluiting (doorverwijzing naar de volgende gang), niet bij de inhoud zelf.

