# LinkedIn Profiel — Course 04: Positioning Cut

"Je profiel is de kaart aan tafel: het bepaalt wat mensen verwachten voordat ze proeven."

**Waarom dit telt:** LinkedIn kijkt of je profiel past bij waar je over post. Hoe duidelijker je profiel je 3–4 onderwerpen uitstraalt, hoe beter je posts bij de juiste mensen terechtkomen.

**Output-regel:** alles in de woorden, het vakgebied en de toon van de klant. Gebruik het merkgeheugen (kernbelofte, doelgroep, positionering, pijlers, toon) en de meegegeven Platformkennis LinkedIn.

## Werkwijze
