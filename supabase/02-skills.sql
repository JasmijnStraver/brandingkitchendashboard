# Origin Story Reeks — Course 01 + 05

"De meeste ondernemers koken met ingrediënten die niet eens van hen zijn." Deze reeks haalt de echte ingrediënten naar boven — het verhaal, de rafelrandjes, de energie die het merk geloofwaardig maakt.

**Output-regel:** dit gaat over de échte, specifieke geschiedenis van déze persoon — geen invuloefening met generieke ondernemersclichés ("ik startte vanuit passie"). Vraag actief door naar concrete momenten, niet alleen de samenvatting.

## Werkwijze
1. Vraag naar 3-4 concrete momenten: het beginpunt (wat deden ze hiervoor, wat frustreerde hen), een kantelmoment, een moeilijke periode of twijfel, en waar ze nu staan.
2. Vraag ook naar een "rafelrandje" — iets kwetsbaars of onverwachts dat de klant meestal niet deelt, maar dat het verhaal menselijk maakt (optioneel, alleen als ze het comfortabel vinden).
3. Bouw een reeks van 6-10 stories die chronologisch of in flashback opbouwen naar nu.

## Structuur per story
- Story 1: hook die nieuwsgierig maakt naar "hoe het begon" of een cliffhanger uit het heden
- Story 2-4: het verleden — concreet, geen samenvatting maar scène-achtig ("het was dinsdagavond, ik zat...")
- Story 5-7: het kantelpunt en wat er veranderde
- Story 8-10: waar ze nu staan + zachte link naar hun aanbod/pijler, zonder dat het als reclame voelt

## Toon
Persoonlijk, kwetsbaar waar gepast, maar niet overdramatisch. Elke story kort (1-3 zinnen) — het is stories, geen essay.

## Output
Story voor story uitgeschreven, met bij elke story een korte indicatie voor beeld/sticker-gebruik (bijv. poll, quote-sticker, foto uit die periode).

## Randgevallen
- Klant wil dit niet te persoonlijk maken: leun dan meer op de professionele reis (carrière-omslag, eerste klant, eerste mislukking) dan op privéleven.
